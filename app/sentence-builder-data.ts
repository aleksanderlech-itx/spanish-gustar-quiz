import type { QuizLevel } from "./quiz-logic.ts";

/**
 * Sentence Builder Items (decision 0013, terms in CONTEXT.md). Each sentence pair is an unchanged row of the
 * Tatoeba corpus (CC BY 2.0 France, see docs/content-sources.md), kept with its attribution. `tokens` is the
 * canonical order; `alsoAccepted` lists every other order that is correct Spanish for the English prompt.
 * Orders that would need a comma are not accepted, since punctuation is never a Token. Ids are permanent
 * (decision 0007): never renumber or reuse one.
 */

export const SENTENCE_BUILDER_GROUPS = [
  "questions",
  "negatives",
  "prepositions",
  "object pronouns",
  "ser and estar",
  "present and past",
  "connectors",
] as const;
export type SentenceBuilderGroup = (typeof SENTENCE_BUILDER_GROUPS)[number];

export type SentenceBuilderItem = {
  id: number;
  group: SentenceBuilderGroup;
  level: QuizLevel;
  /** The prompt shown to the learner. */
  english: string;
  /** The sentence exactly as in the corpus; the canonical Tokens rebuild it. */
  spanish: string;
  /** The canonical order. A Token is a word or a fixed chunk; never punctuation. */
  tokens: string[];
  /** Other orders that are also correct for the prompt, each a permutation of `tokens`. */
  alsoAccepted?: string[][];
  /** The word or phrase in the sentence that the explanation names. */
  cue: string;
  explanation: string;
  /** Tatoeba license and contributor line, as distributed by ManyThings. */
  attribution: string;
};

